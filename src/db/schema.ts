// Canonical schema barrel. Repositories import their tables from here and the
// provider-aware `db` from "@/db", so each repository is written ONCE for both
// backends.
//
// The TYPE identity is the SQLite definitions; the runtime VALUES are whichever
// provider is active. `schema-parity.test.ts` asserts the two dialect schemas
// are structurally interchangeable (same tables/columns/nullability/PKs/unique
// indexes), which is what makes the single cast below sound. The Postgres
// schema is the one structural artifact NOT regenerated by `db:generate`, so the
// parity test is its drift guard.
type AppSchema = typeof sqliteApp &
  typeof sqliteProjectContext &
  typeof sqliteReports &
  typeof sqliteReportTemplates &
  typeof sqliteAudit &
  typeof sqliteAuditSchedule &
  typeof sqliteAuditEvidence &
  typeof sqliteSam &
  typeof sqliteAuth &
  typeof sqliteBilling &
  typeof sqliteGa4 &
  typeof sqliteGsc &
  typeof sqliteTelemetry &
  typeof sqliteAiVisibility &
  typeof sqliteLocalSeo &
  typeof sqliteSiteAuthority &
  typeof sqliteContent &
  typeof sqliteContentEvidence &
  typeof sqliteCompetitorResearch &
  typeof sqliteWebsiteAttempt &
  typeof sqliteFirebaseAuth &
  typeof sqliteWordpress &
  typeof sqliteFreeBacklinks;

const runtimeSchema =
  getDatabaseProvider() === "postgres"
    ? {
        ...pgApp,
        ...pgProjectContext,
        ...pgReports,
        ...pgReportTemplates,
        ...pgAudit,
        ...pgAuditSchedule,
        ...pgAuditEvidence,
        ...pgSam,
        ...pgAuth,
        ...pgBilling,
        ...pgGa4,
        ...pgGsc,
        ...pgTelemetry,
        ...pgAiVisibility,
        ...pgLocalSeo,
        ...pgSiteAuthority,
        ...pgContent,
        ...pgContentEvidence,
        ...pgCompetitorResearch,
        ...pgWebsiteAttempt,
        ...pgFirebaseAuth,
        ...pgWordpress,
        ...pgFreeBacklinks,
      }
    : {
        ...sqliteApp,
        ...sqliteProjectContext,
        ...sqliteReports,
        ...sqliteReportTemplates,
        ...sqliteAudit,
        ...sqliteAuditSchedule,
        ...sqliteAuditEvidence,
        ...sqliteSam,
        ...sqliteAuth,
        ...sqliteBilling,
        ...sqliteGa4,
        ...sqliteGsc,
        ...sqliteTelemetry,
        ...sqliteAiVisibility,
        ...sqliteLocalSeo,
        ...sqliteSiteAuthority,
        ...sqliteContent,
        ...sqliteContentEvidence,
        ...sqliteCompetitorResearch,
        ...sqliteWebsiteAttempt,
        ...sqliteFirebaseAuth,
        ...sqliteWordpress,
        ...sqliteFreeBacklinks,
      };

